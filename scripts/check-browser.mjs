import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();
const errors=[],external=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(!r.url().startsWith('http://127.0.0.1:5177/')&&!r.url().startsWith('data:')) external.push(r.url());});
await mkdir('work/evidence',{recursive:true});
try {
  await page.goto('http://127.0.0.1:5177/');
  await expect(page.getByRole('heading',{name:'Knowledge & Support',exact:true})).toBeVisible();
  await page.screenshot({path:'work/evidence/assistant-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Reopen ready task',exact:true}).click();
  await expect(page.getByText('Retrieved excerpts',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Readiness and handover'}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('dialog')).toContainText('Reopening a completed task withdraws readiness.');
  await page.screenshot({path:'work/evidence/source.png',fullPage:true});
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Readiness and handover'})).toBeFocused();
  await page.getByLabel('Ask the sample library').fill('quantum mars hologram');
  await page.getByRole('button',{name:'Search sources',exact:true}).click();
  await expect(page.getByText('No matching source',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Create support draft',exact:true}).last().click();
  await page.getByLabel('Notes',{exact:true}).fill('Fictional context for review; no submission requested.');
  await page.getByRole('button',{name:'Save draft',exact:true}).click();
  await page.getByRole('navigation').getByRole('button',{name:/Support drafts/}).click();
  await page.getByRole('button',{name:'quantum mars hologram',exact:true}).click();
  await page.getByLabel('Status',{exact:true}).selectOption('Reviewed');
  await page.getByRole('button',{name:'Save draft',exact:true}).click();
  await expect(page.getByText('Reviewed',{exact:true})).toBeVisible();
  await page.reload();
  await page.getByRole('navigation').getByRole('button',{name:/Support drafts/}).click();
  await expect(page.getByText('Reviewed',{exact:true})).toBeVisible();
  await page.screenshot({path:'work/evidence/drafts.png',fullPage:true});
  await page.getByRole('navigation').getByRole('button',{name:/Library/}).click();
  await page.getByPlaceholder('Filter source library').fill('Booking');
  await expect(page.getByRole('button',{name:/Booking rules/})).toHaveCount(1);
  await page.getByLabel('Collection').selectOption('Onboarding');
  await expect(page.getByText('No sources match this filter.',{exact:true})).toBeVisible();
  await page.getByLabel('Collection').selectOption('All');
  await page.getByPlaceholder('Filter source library').fill('');
  await page.screenshot({path:'work/evidence/library.png',fullPage:true});
  for(const width of [320,390,1440,1920]) {
    await page.setViewportSize({width,height:900});
    for(const name of ['Assistant','Library','Support drafts']) {
      await page.getByRole('navigation').getByRole('button',{name:new RegExp('^'+name)}).click();
      expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    }
  }
  await page.setViewportSize({width:390,height:900});
  await page.getByRole('button',{name:'Reset assistant',exact:true}).filter({visible:true}).first().click();
  await page.getByRole('dialog').getByRole('button',{name:'Reset assistant',exact:true}).click();
  await expect(page.getByRole('button',{name:'Reopen ready task',exact:true})).toBeVisible();
  await page.screenshot({path:'work/evidence/assistant-mobile.png',fullPage:true});
  await page.getByLabel('Ask the sample library').fill('x'.repeat(500));
  await page.getByRole('button',{name:'Search sources',exact:true}).click();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Create support draft',exact:true}).click();
  await page.getByLabel('Notes',{exact:true}).fill('x'.repeat(4000));
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Reset assistant',exact:true}).filter({visible:true}).first().click();
  await page.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click();
  await expect(page.getByText('No matching source',{exact:true})).toBeVisible();
  await page.evaluate(()=>sessionStorage.setItem('navrenlo-knowledge-v1',JSON.stringify({turns:[],drafts:Array.from({length:100},(_,i)=>({id:String(i),subject:'Sample '+i,body:'Fictional notes',status:'Draft'}))})));
  await page.reload();
  await page.getByRole('navigation').getByRole('button',{name:/Support drafts/}).click();
  await page.getByRole('button',{name:'New draft',exact:true}).click();
  await expect(page.getByText('Draft limit reached (100). Delete a saved draft before creating another.',{exact:true})).toBeVisible();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('button',{name:'Sample 0',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Delete Sample 0',exact:true}).click();
  await page.getByRole('button',{name:'New draft',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await context.addInitScript(()=>{Storage.prototype.setItem=function(){throw new Error('Storage unavailable');};});
  await page.reload();
  await expect(page.getByRole('alert')).toContainText('Browser storage unavailable');
  expect(errors).toEqual([]);expect(external).toEqual([]);
  await writeFile('work/evidence/browser-report.json',JSON.stringify({passed:true,widths:[320,390,1440,1920],errors,external,checks:['source provenance','unsupported query','Escape focus','draft edit','reload','library filters','mobile reset','long text','cancel reset','draft cap and deletion','storage failure warning']},null,2));
  console.log('Browser checks passed.');
} finally {await browser.close();}
